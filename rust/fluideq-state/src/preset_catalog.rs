//! The factory EQ curves, ported one for one from the reference catalogue.
//!
//! Bands are the same fifteen ISO centres the engine's other curves use, and
//! each row is its own fifteen gains. A row also carries the voicing it was
//! designed on — the model, its amount, the subsonic and mono corners and any
//! fuzz — because a curve played through another model is a different curve.
//! Rows with a dynamic threshold are the repair and scene presets that are
//! meant to act only when a problem arrives.

use serde::{Deserialize, Serialize};

/// Which heading a preset files under in the picker.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum EqPresetGroup {
    Basic,
    Genre,
    Voice,
    Scene,
    Device,
    Character,
    Repair,
    Gaming,
}

impl EqPresetGroup {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Basic => "basic",
            Self::Genre => "genre",
            Self::Voice => "voice",
            Self::Scene => "scene",
            Self::Device => "device",
            Self::Character => "character",
            Self::Repair => "repair",
            Self::Gaming => "gaming",
        }
    }

    pub fn parse(value: &str) -> Option<Self> {
        match value {
            "basic" => Some(Self::Basic),
            "genre" => Some(Self::Genre),
            "voice" => Some(Self::Voice),
            "scene" => Some(Self::Scene),
            "device" => Some(Self::Device),
            "character" => Some(Self::Character),
            "repair" => Some(Self::Repair),
            "gaming" => Some(Self::Gaming),
            _ => None,
        }
    }
}

