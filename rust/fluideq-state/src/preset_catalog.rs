/// The group of a built-in preset by name, for the picker's headings.
pub fn group_of(name: &str) -> Option<EqPresetGroup> {
    PRESET_CATALOG
        .iter()
        .find(|spec| spec.name.eq_ignore_ascii_case(name.trim()))
        .map(|spec| spec.group)
}
